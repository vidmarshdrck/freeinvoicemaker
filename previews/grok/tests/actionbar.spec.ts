import {test,expect} from '@playwright/test';
const url=process.env.PREVIEW_URL || 'http://127.0.0.1:5176/freeinvoicemaker/grok/';
for (const [width,height] of [[360,844],[390,844],[390,568],[1440,844]]) test(`actions occur only after editable notes in document flow ${width}x${height}`,async({browser})=>{
 const context=await browser.newContext({viewport:{width,height}});const page=await context.newPage();await page.goto(url);
 const save=page.getByRole('button',{name:'Save',exact:true});const toolbar=page.getByRole('toolbar',{name:'Document actions'});
 await expect(save).not.toBeInViewport();
 await expect(toolbar).toHaveCSS('position','static');
 const notes=page.getByLabel('Notes / Terms');await notes.fill('Custom note retained');
 await toolbar.scrollIntoViewIfNeeded();
 await expect(save).toBeInViewport(); await expect(page.getByRole('button',{name:'Download PDF',exact:true})).toBeInViewport();
 const bounds=await toolbar.boundingBox();const noteBounds=await notes.boundingBox();expect(bounds!.y).toBeGreaterThanOrEqual(noteBounds!.y+noteBounds!.height);
 for(const button of await toolbar.getByRole('button').all()) expect((await button.boundingBox())!.height).toBeGreaterThanOrEqual(44);
 await page.screenshot({path:`/home/shadrickvidmar/paperclip-handoffs/fim-flow-${process.env.QA_STAGE||'local'}-${width}-${height}.png`});
 await save.click(); await page.reload();await expect(notes).toHaveValue('Custom note retained');
 await page.getByRole('button',{name:'Duplicate',exact:true}).click();await expect(notes).toHaveValue('Custom note retained');
 await page.getByRole('button',{name:'Download PDF',exact:true}).click();await expect(page.locator('.paper')).toContainText('Custom note retained');
 await page.getByRole('button',{name:'Close',exact:true}).click();
 await notes.fill('');await save.click();await page.reload();await expect(notes).toHaveValue('');
 await page.getByRole('button',{name:'Duplicate',exact:true}).click(); await expect(notes).toHaveValue('');
 await page.getByRole('button',{name:'Download PDF',exact:true}).click();await expect(page.locator('.paper')).not.toContainText('Thank you for your business');await expect(page.locator('.paper')).not.toContainText('NOTES');
 await context.close();
});
